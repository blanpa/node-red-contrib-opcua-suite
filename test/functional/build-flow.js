// Methods.ResetAll restores the scalars under Writable/. The arrays are not
// covered by it, so they are written back explicitly. Used before the first
// and after the last test so every run starts from the same data.
function resetTest(tabKey, id, name) {
  twoStep(
    tabKey,
    id,
    name,
    "ft-ep",
    'return { operation: "method", objectNodeId: "ns=1;s=Methods", methodNodeId: "ns=1;s=Methods.ResetAll", inputArguments: [] };',
    "method",
    ERR_GUARD +
      [
        "good('ResetAll', msg.statusCode);",
        "check(Array.isArray(msg.payload) && typeof msg.payload[0] === 'string', 'expected one string output argument');",
        "return carry({ operation: 'writemultiple', items: [",
        "  { nodeId: 'ns=1;s=Arrays.IntArray', value: [10, 20, 30, 40, 50], datatype: 'Int32', arrayType: 'Array' },",
        "  { nodeId: 'ns=1;s=Arrays.DoubleArray', value: [1.1, 2.2, 3.3, 4.4], datatype: 'Double', arrayType: 'Array' },",
        "  { nodeId: 'ns=1;s=Arrays.StringArray', value: ['Alpha', 'Bravo', 'Charlie'], datatype: 'String', arrayType: 'Array' },",
        "  { nodeId: 'ns=1;s=Arrays.BoolArray', value: [true, false, true, false], datatype: 'Boolean', arrayType: 'Array' },",
        "] });",
      ].join("\n"),
    "writemultiple",
    ERR_GUARD +
      "(msg.payload || []).forEach((r, i) => good('restore array ' + i, r.statusCode));\nreturn finish('test data reset');",
  );
}

