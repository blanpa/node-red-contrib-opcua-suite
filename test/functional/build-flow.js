/**
 * Generates examples/15 - Function Test Suite.json.
 *
 * The suite is a self-running Node-RED flow that exercises every node of
 * this package against the node-opcua test server (test-server/server.js),
 * an embedded opcua-server node and an MQTT broker. Tests run strictly one
 * after another:
 *
 *   dispatcher -> link call (dynamic, msg.target = "FT <id>")
 *              -> link in "FT <id>" -> test nodes -> link out (return)
 *              -> dispatcher records the result and starts the next test
 *
 * A test that never answers fails through the link call timeout. Results
 * are served as JSON on GET /opcua-functest/results, which is what
 * test/functional/run.js polls.
 *
 * Usage: node test/functional/build-flow.js
 */

