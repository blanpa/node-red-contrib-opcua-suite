// --- Generic helpers ---

let seq = 0;
function uid(prefix) {
  seq++;
  return `ft-${prefix}-${String(seq).padStart(4, "0")}`;
}

function add(node) {
  flow.push(node);
  return node;
}

// Code shared by every function node that belongs to a test.
function prelude(testId) {
  return [
    "// Generated by test/functional/build-flow.js",
    `const TEST_ID = ${JSON.stringify(testId)};`,
    "const errs = msg && Array.isArray(msg.ftErrs) ? msg.ftErrs.slice() : [];",
    'const tmp = global.get("ft_tmp") || {};',
    'const run = global.get("ft_run") || "0";',
    "function isActive() {",
    '  return global.get("ft_active") === TEST_ID;',
    "}",
    "function check(cond, label) {",
    "  if (!cond) errs.push(label);",
    "}",
    "function eq(label, got, want) {",
    "  if (got !== want) {",
    '    errs.push(label + ": expected " + JSON.stringify(want) + ", got " + JSON.stringify(got));',
    "  }",
    "}",
    "function near(label, got, want, tol) {",
    '  if (typeof got !== "number" || Math.abs(got - want) > (tol || 1e-9)) {',
    '    errs.push(label + ": expected " + want + ", got " + JSON.stringify(got));',
    "  }",
    "}",
    "function good(label, statusCode) {",
    '  if (!String(statusCode).startsWith("Good")) {',
    '    errs.push(label + ": status " + statusCode);',
    "  }",
    "}",
    "function errText(m) {",
    "  const e = m && m.error;",
    '  if (!e) return "";',
    '  return typeof e === "string" ? e : String(e.message || JSON.stringify(e));',
    "}",
    "function carry(obj) {",
    "  obj.ftErrs = errs;",
    "  return obj;",
    "}",
    "function finish(detail) {",
    "  if (!isActive()) return null;",
    '  global.set("ft_active", TEST_ID + ":done");',
    "  return {",
    '    _linkSource: global.get("ft_link"),',
    "    ft: {",
    "      id: TEST_ID,",
    "      ok: errs.length === 0,",
    '      detail: errs.length ? errs.join("; ") : detail || "",',
    "    },",
    "  };",
    "}",
    "function fail(reason) {",
    "  errs.push(reason);",
    "  return finish();",
    "}",
    "// A finished result always leaves through the last output, which is",
    "// wired to the test's return link. The other outputs route messages.",
    "function __route(out, routes) {",
    "  const res = new Array(routes + 1).fill(null);",
    "  (Array.isArray(out) ? out : [out]).forEach((m, i) => {",
    "    if (m == null) return;",
    "    if (m.ft) res[routes] = m;",
    "    else if (i < routes) res[i] = m;",
    "  });",
    "  return res;",
    "}",
    "// --- Test code ---",
    "",
  ].join("\n");
}

// --- Layout helpers ---

const ROW_WIDTH = 1800;

// Rough width of a node as the editor draws it: icon plus label text.
function nodeWidth(n) {
  if (n.type === "link in" || n.type === "link out") return 30;
  const label = n.name || n.type;
  if (n.type === "comment") return Math.max(100, 50 + label.length * 7.5);
  return Math.max(100, 60 + label.length * 8.5);
}

// --- Node type coverage ---

const coverage = new Map(); // node type -> Set of test ids
function use(type, testId) {
  if (!coverage.has(type)) coverage.set(type, new Set());
  coverage.get(type).add(testId);
}

// --- Tabs ---

const tabs = {};
function tab(key, label, info) {
  const t = add({ id: `ft-tab-${key}`, type: "tab", label, info: info || "" });
  t._y = 60;
  t._catchFns = [];
  t._key = key;
  tabs[key] = t;
  return t;
}

/**
 * Declares one test. `build` receives a context to create its nodes. The
 * context lays the nodes out left to right, two rows per test at most.
 */
function test(tabKey, id, name, build) {
  const t = tabs[tabKey];
  const nodes = {};
  const order = [];
  const fnMeta = new Map();
  const ctx = {
    id,
    node(key, def) {
      const n = Object.assign({ id: uid(id.toLowerCase()), z: t.id }, def);
      use(n.type, id);
      if (n.endpoint) use("opcua-endpoint", id);
      if (n.connection) use("opcua-pubsub-connection", id);
      if (!n.wires) n.wires = [[]];
      nodes[key] = n;
      order.push(n);
      add(n);
      return n;
    },
    // `outputs` counts the routing outputs. Every test function gets one
    // more output for its result; ret() marks a routing output as unused.
    fn(key, code, opts = {}) {
      const routes = opts.outputs || 1;
      const n = ctx.node(key, {
        type: "function",
        name: opts.name || key,
        func: "",
        outputs: routes,
        timeout: 0,
        noerr: 0,
        initialize: "",
        finalize: "",
        libs: [],
        wires: Array.from({ length: routes }, () => []),
      });
      fnMeta.set(n, { code, routes });
      t._catchFns.push(n.id);
      return n;
    },
    wire(from, to, port = 0) {
      nodes[from].wires[port].push(nodes[to].id);
    },
    chain(...keys) {
      for (let i = 0; i < keys.length - 1; i++) ctx.wire(keys[i], keys[i + 1]);
    },
    ret(from, port = 0) {
      const meta = fnMeta.get(nodes[from]);
      if (!meta) throw new Error(`${id}: ret() needs a function node`);
      meta.routes = Math.min(meta.routes, port);
    },
    // Sends the message to the shared embedded server node and continues
    // with `to` once the server answered.
    server(key, from, to, fromPort = 0) {
      ctx.node(key, {
        type: "link call",
        name: "embedded server",
        links: ["ft-srv-in"],
        linkType: "static",
        timeout: "10",
      });
      ctx.wire(from, key, fromPort);
      if (to) ctx.wire(key, to);
    },
    delay(key, ms) {
      return ctx.node(key, {
        type: "delay",
        name: `wait ${ms} ms`,
        pauseType: "delay",
        timeout: String(ms),
        timeoutUnits: "milliseconds",
        rate: "1",
        nbRateUnits: "1",
        rateUnits: "second",
        randomFirst: "1",
        randomLast: "5",
        randomUnits: "seconds",
        drop: false,
        allowrate: false,
        outputs: 1,
      });
    },
  };

  const comment = add({
    id: uid(id.toLowerCase()),
    type: "comment",
    z: t.id,
    name: `${id} - ${name}`,
    info: "",
    wires: [],
  });
  const linkIn = add({
    id: uid(id.toLowerCase()),
    type: "link in",
    z: t.id,
    name: `FT ${id}`,
    links: [],
    wires: [[]],
  });
  const retNode = {
    id: uid(id.toLowerCase()),
    type: "link out",
    z: t.id,
    name: `${id} result`,
    mode: "return",
    links: [],
  };

  build(ctx);

  for (const [n, meta] of fnMeta) {
    n.func =
      prelude(id) +
      "const __out = (function () {\n" +
      meta.code +
      `\n})();\nreturn __route(__out, ${meta.routes});\n`;
    n.outputs = meta.routes + 1;
    n.wires = n.wires.slice(0, meta.routes).concat([[retNode.id]]);
  }

  if (!nodes.prep) throw new Error(`${id}: test needs a "prep" node`);
  // The prep node remembers the dispatcher's link call so any later node
  // of this test can return the result to it.
  nodes.prep.func = nodes.prep.func.replace(
    "// --- Test code ---\n",
    '// --- Test code ---\nglobal.set("ft_link", msg._linkSource);\n' +
      "Object.keys(tmp).forEach((k) => delete tmp[k]);\n" +
      'global.set("ft_tmp", tmp);\n',
  );
  linkIn.wires = [[nodes.prep.id]];
  add(retNode);

  // Layout: comment, then link in + nodes left to right, wrapping at
  // ROW_WIDTH. Node-RED places a node by its centre, so x advances by the
  // estimated width of each node.
  comment.x = 20 + nodeWidth(comment) / 2;
  comment.y = t._y;
  const all = [linkIn, ...order, retNode];
  let x = 60;
  let row = 0;
  for (const n of all) {
    const w = nodeWidth(n);
    if (x + w > ROW_WIDTH) {
      x = 60;
      row++;
    }
    n.x = Math.round(x + w / 2);
    n.y = t._y + 50 + row * 70;
    x += w + 60;
  }
  t._y += 50 + (row + 1) * 70 + 40;

  tests.push({ id, name, tab: t.label });
}

