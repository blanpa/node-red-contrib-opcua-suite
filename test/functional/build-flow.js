// --- Node factories ---

function client(ctx, key, ep, op, extra = {}) {
  return ctx.node(
    key,
    Object.assign(
      {
        type: "opcua-client",
        name: op,
        endpoint: ep,
        defaultOperation: op,
        applicationName: "Node-RED Function Test",
        maxReconnectAttempts: 3,
        reconnectDelay: 2000,
        retryAttempts: 0,
        maxOperationRetries: 1,
        retryBackoffMs: 100,
        verboseLog: false,
        // Connect on the first message, so deploy does not race node-opcua's
        // first-run certificate creation and the first test proves it works.
        autoConnect: false,
        unwrapSingle: false,
      },
      extra,
    ),
  );
}

function writers(list) {
  return JSON.stringify(list);
}

/** prep -> client -> chk -> result */
function simple(tabKey, id, name, ep, prepCode, checkCode, op) {
  test(tabKey, id, name, (c) => {
    c.fn("prep", prepCode);
    client(c, "cli", ep, op || "read");
    c.fn("chk", checkCode);
    c.chain("prep", "cli", "chk");
    c.ret("chk");
  });
}

/** prep -> client A -> mid -> client B -> chk -> result */
function twoStep(tabKey, id, name, ep, prepCode, opA, midCode, opB, chkCode) {
  test(tabKey, id, name, (c) => {
    c.fn("prep", prepCode);
    client(c, "a", ep, opA);
    c.fn("mid", midCode);
    client(c, "b", ep, opB);
    c.fn("chk", chkCode);
    c.chain("prep", "a", "mid", "b", "chk");
    c.ret("chk");
  });
}

